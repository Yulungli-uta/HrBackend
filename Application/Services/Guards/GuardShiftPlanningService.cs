    public async Task<GuardDashboardDto> GetDashboardAsync(CancellationToken ct)
    {
        var today = DateOnly.FromDateTime(DateTime.Today);
        var filter = new GuardShiftCalendarFilterDto(today, today, null, null, null, null, null);
        var todayShifts = await GetCalendarAsync(filter, ct);

        var pendingChanges = await _db.GuardShiftChanges
            .Include(c => c.Planning).ThenInclude(p => p!.Location)
            .Include(c => c.OriginalEmployee).ThenInclude(e => e!.People)
            .Include(c => c.ReplacementEmployee).ThenInclude(e => e!.People)
            .Include(c => c.StatusType)
            .Where(c => c.StatusType!.Name == "PENDING")
            .ToListAsync(ct);

        var pendingDtos = pendingChanges.Select(MapChangeToDto).ToList();

        return new GuardDashboardDto(
            todayShifts.Count,
            0,
            pendingDtos.Count,
            0,
            0,
            todayShifts,
            pendingDtos
        );
    }

